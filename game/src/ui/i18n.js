export const DICT = { ru: RU, en: EN };

export function makeT(lang) {
  const d = DICT[lang] ?? RU;
  return (key, vars) => {
    let s = d[key] ?? RU[key] ?? key;
    if (vars && typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', v);
    return s;
  };
}
